#[test]
fn missing_volume_errors_not_truncates() {
    // `archive.part1.rar` ships deliberately incomplete. The List iterator
    // latches `damaged = true` on the first Err and then returns None FOREVER
    // (open_archive.rs:294-315), so a `.filter_map(Result::ok)` here would turn
    // "part 2 is missing" into "a smaller archive" with no error at all: the
    // user extracts a prefix of their files and is told it worked.
    let ar = open("archive.part1.rar");
    let err = ar.entries().err().expect("listing an incomplete set must fail");
    match err {
        OtterzipError::MissingVolume { expected_name, .. } => {
            assert_eq!(expected_name.as_deref(), Some("archive.part2.rar"));
        }
        other => panic!("expected MissingVolume, got {other:?}"),
    }
}

#[test]
fn missing_volume_extract_errors_and_leaves_no_scratch() {
    let td = tempdir().unwrap();
    let out = td.path().join("out");
    let ar = open("archive.part1.rar");
    let err = extract(&ar, &out).unwrap_err();

    assert!(matches!(err, OtterzipError::MissingVolume { .. }), "got {err:?}");
    assert!(walk(&out).is_empty(), "a failed set must publish nothing");
    assert!(scratch_dirs(&out).is_empty(), "scratch leaked: {:?}", scratch_dirs(&out));
}

#[test]
fn non_first_volume_redirects_to_first_part() {
    // Right-clicking `foo.part03.rar` must extract the whole set, so
    // `RarBackend::open` applies `first_part()` once at open.
    //
    // Proven by redirection rather than by inspecting a path: part 1 and part 2
    // are DIFFERENT archives with different entry names, and we open part 2. If
    // the redirect is live we see part 1's entry; if it silently regressed we
    // would see part 2's own, and the test could not be fooled by a `first_part`
    // that returned its input unchanged.
    let td = tempdir().unwrap();
    let p1 = td.path().join("redirect.part00001.rar");
    let p2 = td.path().join("redirect.part00002.rar");
    std::fs::copy(fx("version.rar"), &p1).unwrap(); // entry: VERSION
    std::fs::copy(fx("solid.rar"), &p2).unwrap(); // entry: .gitignore

    let ar = Archive::open(&p2, OpenMode::Read).unwrap();
    assert_eq!(
        entry_paths(&ar),
        vec!["VERSION"],
        "opening part 2 must read part 1"
    );

    let out = td.path().join("out");
    extract(&ar, &out).unwrap();
    assert_eq!(std::fs::read(out.join("VERSION")).unwrap(), b"unrar-0.4.0");
}

#[test]
fn non_first_volume_without_its_first_part_errors() {
    // `100M.part00002.rar` ships without a part 1, so the redirect lands on a
    // file that does not exist -> EOpen@Open.
    //
    // DOCUMENTS A KNOWN ROUGH EDGE, it does not bless it: per plan §3.2
    // `(EOpen, _)` maps to Io(NotFound), so the user is told "could not open RAR
    // archive" when the truthful answer is MissingVolume { expected:
    // 100M.part00001.rar } — arguably the single most common real RAR mistake.
    // Left faithful to the plan; if that mapping is revisited, this assertion is
    // the one to change, and changing it is an improvement.
    let err = Archive::open(fx("100M.part00002.rar"), OpenMode::Read).unwrap_err();
    match err {
        OtterzipError::Io(e) => assert_eq!(e.kind(), std::io::ErrorKind::NotFound),
        other => panic!("expected Io(NotFound), got {other:?}"),
    }
}

