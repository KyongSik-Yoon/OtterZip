#[test]
fn long_password_truncates_not_errors() {
    // Regression guard. crypt.cpp:57 truncates at MAXPASSWORD-1 "For
    // compatibility with existing archives", and WinRAR does the same — so a
    // long password must be *tried and rejected*, never refused up front.
    // Refusing would mean declining archives that open fine everywhere else.
    let long = "x".repeat(200);
    // Either open refuses it (the regression we are guarding against) or it gets
    // as far as being tried and found wrong (correct). Collapse both to the one
    // error we then judge.
    let err = open_pw("crypted.rar", &long)
        .map(|ar| {
            let td = tempdir().unwrap();
            extract(&ar, &td.path().join("out"))
                .expect_err("a 200-char password is still the wrong password")
        })
        .unwrap_or_else(|e| e);

    assert!(
        matches!(err, OtterzipError::WrongPassword),
        "a long password must be truncated and tried, not rejected: {err:?}"
    );
    assert!(
        !matches!(err, OtterzipError::InvalidArgument(_)),
        "regression: a length gate was added; WinRAR accepts these"
    );
}

#[test]
fn non_ascii_password_is_never_silently_mangled() {
    // `RARSetPassword` is the ANSI entry point: unrar runs
    // MultiByteToWideChar(CP_ACP, ..) (unicode.cpp:90) on whatever bytes it is
    // handed, while the crate hands it raw UTF-8. On CP949/932/936 that
    // silently turns a correct non-ASCII password into a different one —
    // "wrong password" on archives WinRAR opens fine. `password_bytes_for_unrar`
    // pre-encodes to the ACP so unrar's decode round-trips.
    //
    // WHAT THIS CAN AND CANNOT PROVE: proving the round trip *succeeds* needs a
    // RAR authored with a non-ASCII password, which needs RARLAB's `rar` (plan
    // §4.2 flags this P0 gap). What it does pin is that both branches are
    // *reachable and typed*: either the ACP encodes the password and unrar
    // rejects it as wrong (CP949 here), or the ACP cannot represent it and we
    // fail LOUDLY. What must never happen is a mangled password reaching unrar
    // as `Corrupted`/`BackendError`, or a panic.
    let outcome = open_pw("crypted.rar", "암호")
        .map(|ar| {
            let td = tempdir().unwrap();
            extract(&ar, &td.path().join("out")).expect_err("암호 is not the password")
        })
        .unwrap_or_else(|e| e);

    match outcome {
        // ACP encoded it (e.g. CP949): the conversion ran, unrar decoded it back
        // and simply says no.
        OtterzipError::WrongPassword => {}
        // ACP cannot represent it (e.g. CP1252): the `used_default` probe fired.
        // Loud is the whole point — silently sending "??" would report a wrong
        // password for a correct one.
        OtterzipError::InvalidArgument(_) => {}
        other => panic!("non-ASCII password produced an untyped failure: {other:?}"),
    }
}

