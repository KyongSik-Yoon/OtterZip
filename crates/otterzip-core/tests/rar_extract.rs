#[test]
fn traversal_entry_blocked() {
    // The entry is named `..\..\a` and unrar hands it back VERBATIM — its own
    // cleaning does not strip `..`. So this is the only thing between the
    // archive and the filesystem, not a second line of defence.
    //
    // dest_root is nested two deep so the escape has somewhere real to land:
    // `<td>/deep/out/../../a` resolves to `<td>/a`.
    let td = tempdir().unwrap();
    let out = td.path().join("deep").join("out");
    let ar = open("traversal.rar");

    assert_eq!(entry_paths(&ar), vec!["../../a"], "normalised, not yet judged");

    let err = extract(&ar, &out).unwrap_err();
    match err {
        OtterzipError::PathTraversalBlocked(p) => assert_eq!(p, "../../a"),
        other => panic!("expected PathTraversalBlocked, got {other:?}"),
    }
    assert!(!td.path().join("a").exists(), "escaped to <td>/a");
    assert!(!td.path().join("deep").join("a").exists(), "escaped to <td>/deep/a");
    assert!(
        walk(td.path()).is_empty(),
        "nothing may be written anywhere: {:?}",
        walk(td.path())
    );
    assert!(scratch_dirs(&out).is_empty(), "scratch leaked on the traversal path");
}

#[test]
fn backslash_names_normalize() {
    // RAR stores `\` on Windows-created archives. Normalising is CLAUDE.md rule
    // 3, but it is also required for correctness: `__validate_component` rejects
    // an embedded backslash, so an unnormalised `a\b\c.t` would be misreported
    // as *traversal* — a false positive on a perfectly ordinary archive.
    let td = tempdir().unwrap();
    let out = td.path().join("out");
    let ar = open("backslash.rar");

    assert_eq!(entry_paths(&ar), vec!["a/b/c.t"]);

    let report = extract(&ar, &out).unwrap();
    assert_eq!(report.entries_extracted, 1);
    // Real nested directories, not one file with backslashes in its name.
    assert!(out.join("a").is_dir());
    assert!(out.join("a").join("b").is_dir());
    assert_eq!(
        std::fs::read(out.join("a").join("b").join("c.t")).unwrap(),
        b"unrar-0.4.0"
    );
}

#[test]
fn absolute_path_entry_is_contained() {
    // The entry is authored as `C:\ev.t`, but unrar rewrites the drive colon and
    // hands back `C_\ev.t`. Documents the boundary precisely: our colon check is
    // NOT what saves us from absolute paths here — unrar got there first — so
    // the `..` rejection in `traversal_entry_blocked` is carrying the load. If
    // unrar ever stops sanitising, this test flips to a containment failure and
    // tells us.
    let td = tempdir().unwrap();
    let out = td.path().join("out");
    let ar = open("absolute.rar");

    assert_eq!(entry_paths(&ar), vec!["C_/ev.t"]);
    extract(&ar, &out).unwrap();

    assert!(out.join("C_").join("ev.t").exists());
    assert!(
        walk(&out).iter().all(|p| out.join(p).starts_with(&out)),
        "entry escaped dest_root"
    );
}

#[test]
fn symlink_entry_skipped_and_contained() {
    // `symlink.rar` is `version.rar` with ATTR patched to 0xa1ff (S_IFLNK|0777)
    // — the exact bits unrar itself derives FSREDIR_UNIXSYMLINK from
    // (arcread.cpp:307-309).
    //
    // Matters because `extract_to` sets CurConvertSymlinkPaths=false, turning
    // OFF unrar's own symlink-escape defence, while still creating REAL reparse
    // points. We can neither ask unrar to skip links nor see redir_type through
    // the wrapper — so the entry must be skipped, and its "contents" (the link
    // target) must never be written as a file.
    let td = tempdir().unwrap();
    let out = td.path().join("out");
    let ar = open("symlink.rar");

    let entries = ar.entries().unwrap().collect::<Result<Vec<_>, _>>().unwrap();
    assert!(entries[0].is_symlink, "fixture must present as a link record");

    let report = extract(&ar, &out).unwrap();
    assert_eq!(report.entries_extracted, 0, "a link record must not be extracted");
    assert_eq!(report.entries_skipped, 1);
    assert!(
        report
            .warnings
            .iter()
            .any(|w| matches!(w, ExtractWarning::SymlinkSkipped { .. })),
        "skipping must be reported, not silent: {:?}",
        report.warnings
    );
    assert!(!out.join("VERSION").exists(), "link target written as a file");
    assert!(walk(&out).is_empty(), "nothing may be published: {:?}", walk(&out));
    assert!(scratch_dirs(&out).is_empty());
}

