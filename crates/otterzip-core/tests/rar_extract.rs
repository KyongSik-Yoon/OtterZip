#[test]
fn scratch_is_cleaned_on_cancel() {
    // The scratch is created before the loop, so it is live when the first
    // progress callback runs. Cancelling there must leave dest_root pristine —
    // `Scratch`'s Drop is what makes "cancel" mean "nothing happened" rather
    // than "half a file with a real name".
    let td = tempdir().unwrap();
    let out = td.path().join("out");
    let mut cancel = |_: &Progress| false;
    let ar = open("version.rar");

    let err = ar
        .extract_all(&extract_opts(&out), Some(&mut cancel))
        .unwrap_err();

    assert!(matches!(err, OtterzipError::Canceled), "got {err:?}");
    assert!(scratch_dirs(&out).is_empty(), "scratch leaked: {:?}", scratch_dirs(&out));
    assert!(walk(&out).is_empty(), "cancel published files: {:?}", walk(&out));
}

#[test]
fn scratch_is_cleaned_on_mid_extract_error() {
    // traversal.rar fails AFTER the scratch exists (the missing-volume case
    // fails during the metadata pass, before it is created), so this is the case
    // that actually exercises Drop on the error path.
    let td = tempdir().unwrap();
    let out = td.path().join("out");
    let ar = open("traversal.rar");

    assert!(extract(&ar, &out).is_err());
    assert!(scratch_dirs(&out).is_empty(), "scratch leaked: {:?}", scratch_dirs(&out));
}

