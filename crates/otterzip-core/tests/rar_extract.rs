// declared size is a lie, and it is the attacker's lie
// ---------------------------------------------------------------------------

#[test]
fn inflated_declared_size_does_not_become_a_resource_cost() {
    // `bigdecl.rar` declares UNP_SIZE = 100 MiB over 11 real bytes.
    //
    // `extract_entry` used to branch on that number: above 64 MiB it staged the
    // entry through `extract_to` into %TEMP% and let unrar `Prealloc(UnpSize)`
    // claim the DECLARED size up front (extract.cpp:773-780) — so a header field
    // the archive chose decided how much of C: to consume, on `Archive::test`,
    // the one API a user runs precisely because they distrust the archive. None
    // of `extract_all_inner`'s gates covered it: RAR overrides
    // `extract_all_streaming`, so `Archive::test` and `read_entry` never meet
    // them.
    //
    // Now every size goes through `read()` (RAR_TEST), which creates no file and
    // preallocates nothing, and whose `Vec` grows with the REAL data. The unit
    // test `extract_entry_never_stages_through_temp` pins the %TEMP% half; this
    // pins the contract a caller sees: the lie yields 11 bytes, not 100 MiB.
    let ar = open("bigdecl.rar");
    let entries = ar.entries().unwrap().collect::<Result<Vec<_>, _>>().unwrap();
    assert_eq!(
        entries[0].uncompressed_size,
        100 * 1024 * 1024,
        "fixture must declare 100 MiB or it proves nothing"
    );

    let mut buf = Vec::new();
    std::io::Read::read_to_end(&mut ar.read_entry("VERSION").unwrap(), &mut buf).unwrap();
    assert_eq!(buf, b"unrar-0.4.0", "only the real bytes may be produced");

    // And `Archive::test` — the caller that has no cap of its own — agrees.
    let report = ar.test::<fn(&Progress) -> bool>(None).unwrap();
    assert_eq!(report.entries_tested, 1);
}

