//! RAR backend integration tests — `docs/05-build/rar-backend-plan.md` §4.
//!
//! RAR is **extraction only** (RARLAB's UnRAR licence forbids using the source
//! to build a RAR-compatible archiver), so unlike every other backend we cannot
//! author a fixture with our own writer. Fixtures come from two places:
//!
//! 1. `tests/fixtures/rar/*.rar` copied verbatim out of the `unrar` crate's own
//!    `data/` directory — real RARLAB-produced archives, including the RAR3
//!    entry-encrypted and RAR5 header-encrypted cases.
//! 2. `traversal.rar` / `backslash.rar` / `absolute.rar` / `symlink.rar`,
//!    generated by `tools/make-rar-fixtures.py`, which patches `version.rar`'s
//!    entry header in place and recomputes the RAR3 header CRC. Real unrar reads
//!    them back, which is the point: unrar's own parser is the judge of whether
//!    the hostile names we claim to defend against are actually reachable.
//!
//! The three things worth knowing before touching these tests:
//!
//! * **A wrong password on RAR3 is byte-identical to corruption.** unrar returns
//!   `BadData@Process` ("File CRC error") for both, because RAR3 has no password
//!   verifier. `map_unrar` therefore uses a heuristic guarded on *we supplied a
//!   password* AND *this entry is encrypted*. [`rar3_wrong_password_is_not_corrupted`]
//!   is the test that pins it; if it ever regresses to `Corrupted`, a user with a
//!   typo gets told their archive is destroyed.
//! * **Hostile filenames arrive verbatim.** `..\..\a` survives unrar's own
//!   cleaning ([`traversal_entry_blocked`]), so our guard is the only defence,
//!   not belt-and-braces.
//! * **Nothing here may create a RAR.** [`writer_still_refuses_rar`] is a licence
//!   guard, not a scope guard.

use std::path::{Path, PathBuf};

use otterzip_core::archive::ExtractWarning;
use otterzip_core::{
    Archive, ArchiveFormat, CreateOptions, ExtractOptions, OpenMode, OtterzipError,
    OverwritePolicy, Progress,
};
use tempfile::tempdir;

// ---------------------------------------------------------------------------
// helpers
// ---------------------------------------------------------------------------

fn fx(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("fixtures")
        .join("rar")
        .join(name)
}

fn open(name: &str) -> Archive {
    Archive::open(fx(name), OpenMode::Read).unwrap_or_else(|e| panic!("open {name}: {e:?}"))
}

fn open_pw(name: &str, pw: &str) -> otterzip_core::Result<Archive> {
    Archive::open_with_password(fx(name), OpenMode::Read, pw.to_owned())
}

fn extract_opts(dest: &Path) -> ExtractOptions {
    ExtractOptions {
        destination: dest.to_path_buf(),
        overwrite: OverwritePolicy::Always,
        ..Default::default()
    }
}

fn extract(ar: &Archive, dest: &Path) -> otterzip_core::Result<otterzip_core::ExtractReport> {
    ar.extract_all::<fn(&Progress) -> bool>(&extract_opts(dest), None)
}

fn entry_paths(ar: &Archive) -> Vec<String> {
    ar.entries()
        .unwrap()
        .map(|e| e.unwrap().path)
        .collect::<Vec<_>>()
}

/// Every regular file under `root`, as paths relative to it.
fn walk(root: &Path) -> Vec<PathBuf> {
    fn go(dir: &Path, root: &Path, out: &mut Vec<PathBuf>) {
        let Ok(rd) = std::fs::read_dir(dir) else {
            return;
        };
        for e in rd.flatten() {
            let p = e.path();
            if p.is_dir() {
                go(&p, root, out);
            } else if let Ok(rel) = p.strip_prefix(root) {
                out.push(rel.to_path_buf());
            }
        }
    }
    let mut out = Vec::new();
    go(root, root, &mut out);
    out.sort();
    out
}

/// The scratch dirs `Scratch::new_in` creates inside `dest_root`. Every one of
/// these that survives a call is a leak — `Scratch`'s `Drop` is what keeps a
/// failed extract from littering the user's output folder with half-written
/// files, which for a multi-volume-first format is the *common* path, not a
/// corner case.
fn scratch_dirs(dest_root: &Path) -> Vec<String> {
    let Ok(rd) = std::fs::read_dir(dest_root) else {
        return Vec::new();
    };
    rd.flatten()
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| n.starts_with(".otterzip-rar-"))
        .collect()
}

