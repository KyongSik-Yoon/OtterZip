#[test]
fn rar3_wrong_password_is_not_corrupted() {
    // ** THE ONE. **
    //
    // RAR3 has no password verifier: unrar decrypts to garbage, the CRC fails,
    // and the DLL returns `BadData@Process` — the SAME code as genuine
    // corruption, with the same "File CRC error" text. unrar's own UI can tell
    // them apart (extract.cpp:910-926 picks UIERROR_CHECKSUMENC over
    // UIERROR_CHECKSUM) but the DLL does not export the distinction, so
    // `map_unrar` guesses, guarded on `password supplied && entry encrypted`.
    //
    // It guesses in the recoverable direction on purpose. If this ever
    // regresses to `Corrupted`, a user who fat-fingered their password is told
    // their archive is destroyed — and there is no way for them to find out
    // otherwise.
    let td = tempdir().unwrap();
    let ar = open_pw("crypted.rar", "WRONG-PASSWORD").unwrap();
    let err = extract(&ar, &td.path().join("out")).unwrap_err();

    assert!(
        matches!(err, OtterzipError::WrongPassword),
        "wrong password on RAR3 must map to WrongPassword, got {err:?}"
    );
    assert!(
        !matches!(err, OtterzipError::Corrupted { .. }),
        "regression: the BadData heuristic stopped firing"
    );
}

#[test]
fn unencrypted_rar_is_not_encrypted() {
    // The negative half of the heuristic's guard: `entry.encrypted` is what
    // stops a genuinely corrupt *plain* entry being reported as a password
    // problem. If this ever returns true the guard is meaningless.
    assert!(!open("version.rar").is_encrypted().unwrap());
    assert!(!open("solid.rar").is_encrypted().unwrap());
}

