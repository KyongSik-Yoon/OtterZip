#[test]
fn writer_still_refuses_rar() {
    // NOT a scope guard. The RARLAB UnRAR licence forbids using the source to
    // develop a RAR-compatible archiver, so `writer.rs`'s `F::Rar =>
    // FeatureDisabled` is a LEGAL constraint. Reading RAR does not relax it.
    // Duplicated from sprint4_writer.rs on purpose: it must fail here too, next
    // to the code that made reading possible.
    let td = tempdir().unwrap();
    let opts = CreateOptions {
        format: ArchiveFormat::Rar,
        ..Default::default()
    };
    let err = Archive::create(td.path().join("nope.rar"), opts).unwrap_err();
    assert!(matches!(err, OtterzipError::FeatureDisabled(_)), "got {err:?}");
}

#[test]
fn rar_update_mode_refused() {
    // The other half of extract-only: no in-place modification either.
    let err = Archive::open(fx("version.rar"), OpenMode::Update).unwrap_err();
    assert!(matches!(err, OtterzipError::FeatureDisabled(_)), "got {err:?}");
}
